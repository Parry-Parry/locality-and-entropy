#!/usr/bin/env python3
"""Step 5c: drop-in replacement files for every table/paragraph that changes.

Full replacements, never diffs. Structure, column order, row order, numeric
formatting and the \\phantom padding scheme are byte-for-byte those of
main_intermediate/table.tex -- only the equivalence superscripts change.

As in the original, the equivalence classes are computed on nDCG@10 and applied
to every measure in that (group, architecture), and classes are connected
components of the pairwise graph. PROTOCOL.md records why that last step is
retained rather than fixed.

Usage:
    python recompute/make_dropins.py
"""

from __future__ import annotations

import os

import networkx as nx
import pandas as pd

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RECOMPUTE = os.path.join(REPO, "recompute")
DROPIN = os.path.join(RECOMPUTE, "dropin")

DOMAIN_ORDER = ["Random", "BM25", "Cross-Encoder", "Ensemble"]
LETTER = {d: "abcd"[i] for i, d in enumerate(DOMAIN_ORDER)}
LOSS_ORDER = ["LCE", "RankNet", "marginMSE", "KL"]

# (group, arch, metric) per column, in printed order
COLUMNS = [
    ("dl19", "BE", "nDCG@10"),
    ("dl19", "BE", "AP(rel=2)"),
    ("dl19", "CE", "nDCG@10"),
    ("dl19", "CE", "AP(rel=2)"),
    ("dl20", "BE", "nDCG@10"),
    ("dl20", "BE", "AP(rel=2)"),
    ("dl20", "CE", "nDCG@10"),
    ("dl20", "CE", "AP(rel=2)"),
    ("beir", "BE", "nDCG@10"),
    ("beir", "CE", "nDCG@10"),
]

HEADER = r"""\begin{table}[t]
  \centering
  \footnotesize
  \setlength{\tabcolsep}{3pt}
  \begin{tabular}{llcccccccccc}
  \toprule
    Loss & Domain & \multicolumn{4}{c}{TREC DL'19} & \multicolumn{4}{c}{TREC DL'20} & \multicolumn{2}{c}{BEIR} \\
  \cmidrule(lr){3-6}\cmidrule(lr){7-10}\cmidrule(lr){11-12}
    &  & BE nDCG & BE MAP & CE nDCG & CE MAP & BE nDCG & BE MAP & CE nDCG & CE MAP & BE nDCG & CE nDCG \\
  \midrule"""

FOOTER = r"""  \bottomrule
  \end{tabular}
\end{table}"""


def components(res: pd.DataFrame, eq_col: str) -> dict:
    """(group, arch) -> {domain: set of equivalent partners}, via components."""
    out = {}
    ndcg = res[res["measure"] == "nDCG@10"]
    for (group, arch), sub in ndcg.groupby(["group", "arch"]):
        graph = nx.Graph()
        graph.add_nodes_from(DOMAIN_ORDER)
        for _, row in sub[sub[eq_col]].iterrows():
            graph.add_edge(row["baseline"], row["candidate"])
        membership = {}
        for comp in nx.connected_components(graph):
            for d in comp:
                membership[d] = set(comp) - {d}
        out[(group, arch)] = membership
    return out


def superscript(partners: set) -> str:
    """Letters of the other members, padded to three characters as in the original."""
    letters = "".join(LETTER[d] for d in DOMAIN_ORDER if d in partners)
    return f"\\textsuperscript{{{letters}\\phantom{{{'a' * (3 - len(letters))}}}}}"


def build_table(res: pd.DataFrame, means: pd.DataFrame, eq_col: str,
                margin_label: str) -> str:
    comps = components(res, eq_col)
    lines = [HEADER]
    for loss in LOSS_ORDER:
        for domain in DOMAIN_ORDER:
            cells = []
            for group, arch, metric in COLUMNS:
                sel = means[
                    (means["group"] == group)
                    & (means["arch"] == arch)
                    & (means["measure"] == metric)
                    & (means["domain"] == domain)
                    & (means["loss"] == loss)
                ]
                value = f"{sel['value'].iloc[0]:.3f}" if len(sel) else "n/a"
                partners = comps.get((group, arch), {}).get(domain, set())
                cells.append(f"{value}{superscript(partners)}")
            lines.append(f"  {loss} & {domain} & " + " & ".join(cells) + r" \\")
    lines.append(FOOTER)

    caption = (
        r"\caption{Ranking effectiveness across loss criteria and sampling "
        r"domains. In-domain effectiveness is evaluated on TREC Deep Learning "
        r"test collections, and out-of-domain effectiveness is evaluated on "
        r"the BEIR benchmark (per-dataset effectiveness is shown in Section "
        r"4.4.6). Superscripts denote statistical equivalence via a "
        r"\emph{paired} TOST on per-query differences, with margin "
        r"$\theta = \varepsilon\,\mu_{\text{baseline}}$ at "
        f"$\\varepsilon = {margin_label}$ and $\\alpha = 0.05$.}}"
    )
    body = "\n".join(lines)
    return (
        "% DROP-IN REPLACEMENT -- generated by recompute/make_dropins.py\n"
        "% The \\label below is a PLACEHOLDER: the LaTeX source was not\n"
        "% available, so the thesis's real label could not be read. Replace it\n"
        "% with the label currently on Table 4.1 before applying.\n"
        f"{body}\n  {caption}\n  \\label{{tab:ch4-main-results}}\n"
    )


def main() -> None:
    os.makedirs(DROPIN, exist_ok=True)

    res = pd.read_csv(os.path.join(RECOMPUTE, "results", "tost_table_4_1.csv"))

    # means, recomputed from the same per-query data (never retyped)
    frames = []
    for group in ["dl19", "dl20", "beir"]:
        df = pd.read_csv(
            os.path.join(REPO, "main_intermediate", f"perquery_{group}.tsv.gz"),
            sep="\t",
            low_memory=False,
        )
        df = df[df["arch"] != "CE-Teacher"]
        g = (
            df.groupby(["loss", "arch", "domain", "measure"])["value"]
            .mean()
            .reset_index()
        )
        g["group"] = group
        frames.append(g)
    means = pd.concat(frames, ignore_index=True)

    for eq_col, label, fname in [
        ("equivalent", "0.01", "table_4_1_eps_1pct.tex"),
        ("equivalent_at_5pct", "0.05", "table_4_1_eps_5pct.tex"),
        ("equivalent_at_10pct", "0.10", "table_4_1_eps_10pct.tex"),
    ]:
        tex = build_table(res, means, eq_col, label)
        with open(os.path.join(DROPIN, fname), "w", encoding="utf-8") as fh:
            fh.write(tex)
        n_eq = int(res[res["measure"] == "nDCG@10"][eq_col].sum())
        print(f"{fname}: {n_eq} equivalent nDCG@10 pairs drive the superscripts")

    print(f"\nwrote {os.path.relpath(DROPIN, REPO)}/")


if __name__ == "__main__":
    main()
