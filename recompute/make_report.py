def appendix_tost() -> str:
    return (
        "% DROP-IN replacement for the appendix TOST definition.\n"
        "% The original defined theta = |mu2 - mu1| * eps -- a margin derived\n"
        "% from the observed difference -- and specified independent samples.\n"
        "% Generated by recompute/make_report.py.\n"
        "\\subsection*{TOST test}\n\n"
        "A two one-sided t-test (TOST) assesses whether two systems are "
        "equivalent to within a margin fixed in advance. Because the same "
        "queries are run through both systems, the test is applied to the "
        "\\emph{paired} per-query differences "
        "$d_q = m(\\text{candidate}, q) - m(\\text{baseline}, q)$ rather than "
        "to the two score sets as independent samples; pairing removes the "
        "between-query variance that dominates retrieval effectiveness.\n\n"
        "We fix an equivalence margin "
        "$\\theta = \\varepsilon\\,\\mu_{\\text{baseline}}$, a proportion "
        "$\\varepsilon$ of the baseline's mean effectiveness, with "
        "$\\varepsilon = 0.01$ and $\\alpha = 0.05$. Note that $\\theta$ is "
        "defined relative to the baseline mean and is chosen before the "
        "comparison is made; it is not a function of the observed difference. "
        "We then test two one-sided hypotheses, "
        "$H_{01}: \\mathbb{E}[d] \\leq -\\theta$ and "
        "$H_{02}: \\mathbb{E}[d] \\geq \\theta$, each at level $\\alpha$ "
        "using a paired $t$-test. Equivalence is concluded only if "
        "\\emph{both} are rejected, which is identical to requiring that the "
        "$90\\%$ confidence interval of $\\mathbb{E}[d]$ lie entirely within "
        "$(-\\theta, \\theta)$. Rejecting both at level $\\alpha$ gives an "
        "overall type-I error rate of $\\alpha$, not $2\\alpha$.\n\n"
        "Failing to conclude equivalence is not evidence of a difference, and "
        "a non-significant difference is not evidence of equivalence; the two "
        "questions are separate, so we also report a two-sided paired "
        "$t$-test. For each comparison we report "
        "$\\varepsilon^{*} = \\max(|\\text{CI}_{\\text{low}}|, "
        "|\\text{CI}_{\\text{high}}|) / \\mu_{\\text{baseline}}$, the "
        "smallest margin the data support, so that a reader may apply any "
        "margin they consider material.\n"
    )


