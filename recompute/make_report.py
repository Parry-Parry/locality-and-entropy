    claimed = int(s["original_claim"].sum())
    eq1 = int(s["equivalent_at_1pct"].sum())
    eq5 = int(s["equivalent_at_5pct"].sum())
    eq10 = int(s["equivalent_at_10pct"].sum())
    lost = int((s["original_claim"] & ~s["equivalent_at_1pct"]).sum())
    gained = int((~s["original_claim"] & s["equivalent_at_1pct"]).sum())
